export const COUNTRIES: Country[] = RAW_COUNTRIES.map(([code, name]) => ({
  code,
  name,
  isEurozone: EUROZONE_CODES.has(code),
})).sort((a, b) => a.name.localeCompare(b.name, "fr"));

export function isEurozoneCountry(code: string | null | undefined): boolean {
  return EUROZONE_CODES.has((code ?? "").toUpperCase());
}

export function countryName(code: string | null | undefined): string {
  return COUNTRIES.find((c) => c.code === code)?.name ?? code ?? "";
}
